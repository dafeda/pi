"""Regenerate the README's reservoir.svg using only the Python standard library.

From the repository root:
    python3 scientific-harness/assets/generate_reservoir.py

Edit the geometry, permeability, and color constants below, then rerun the script.
"""

from pathlib import Path
from textwrap import dedent

DOMAIN_LENGTH_M = 100.0
BAND_CENTER_M = 50.0
BAND_WIDTH_M = 10.0
BACKGROUND_MD = 100.0
BAND_MD = 1.0

BACKGROUND_COLOR = "#dceef2"
BAND_COLOR = "#245576"
TEXT_COLOR = "#243746"
AXIS_COLOR = "#526372"


def main() -> None:
    """Write the reservoir map beside this script, independent of the working directory."""
    band_start_m = BAND_CENTER_M - BAND_WIDTH_M / 2
    band_end_m = BAND_CENTER_M + BAND_WIDTH_M / 2
    pixels_per_m = 360 / DOMAIN_LENGTH_M
    band_start_x = 80 + band_start_m * pixels_per_m
    band_end_x = 80 + band_end_m * pixels_per_m
    band_center_x = (band_start_x + band_end_x) / 2
    band_width_px = band_end_x - band_start_x
    left_label_x = (80 + band_start_x) / 2
    right_label_x = (band_end_x + 440) / 2

    svg = dedent(
        f"""\
        <!-- Generated by generate_reservoir.py; edit that script and rerun it. -->
        <svg xmlns="http://www.w3.org/2000/svg" width="520" height="520"
             viewBox="0 0 520 520" role="img" aria-labelledby="title description">
          <title id="title">Fixed synthetic reservoir permeability</title>
          <desc id="description">
            Top-down map of a {DOMAIN_LENGTH_M:g} m by {DOMAIN_LENGTH_M:g} m reservoir.
            The background permeability is {BACKGROUND_MD:g} mD.
            A {BAND_WIDTH_M:g} m wide, {BAND_MD:g} mD vertical band spans
            x = {band_start_m:g}–{band_end_m:g} m and the full y-direction.
          </desc>
          <rect width="520" height="520" fill="#ffffff" />
          <g font-family="Arial, Helvetica, sans-serif" fill="{TEXT_COLOR}">
            <text x="260" y="30" text-anchor="middle" font-size="20" font-weight="600">
              Hidden permeability field
            </text>

            <path d="M {band_start_x:g} 84 V 66 H {band_end_x:g} V 84"
                  fill="none" stroke="{AXIS_COLOR}" stroke-width="1.5" />
            <text x="{band_center_x:g}" y="56" text-anchor="middle" font-size="14">
              {BAND_WIDTH_M:g} m
            </text>

            <rect id="domain" x="80" y="90" width="360" height="360"
                  fill="{BACKGROUND_COLOR}" />
            <rect id="band" x="{band_start_x:g}" y="90" width="{band_width_px:g}"
                  height="360" fill="{BAND_COLOR}" />
            <rect x="80" y="90" width="360" height="360" fill="none"
                  stroke="{AXIS_COLOR}" stroke-width="1.5" />

            <g text-anchor="middle" font-size="16">
              <text x="{left_label_x:g}" y="262">Background</text>
              <text x="{left_label_x:g}" y="286" font-size="20" font-weight="600">
                {BACKGROUND_MD:g} mD
              </text>
              <text x="{right_label_x:g}" y="262">Background</text>
              <text x="{right_label_x:g}" y="286" font-size="20" font-weight="600">
                {BACKGROUND_MD:g} mD
              </text>
              <text x="{band_center_x:g}" y="276"
                    transform="rotate(-90 {band_center_x:g} 270)" fill="#ffffff"
                    font-size="20" font-weight="600">{BAND_MD:g} mD</text>
            </g>

            <path d="M 80 450 v 6 M 260 450 v 6 M 440 450 v 6
                     M 80 450 h -6 M 80 270 h -6 M 80 90 h -6"
                  fill="none" stroke="{AXIS_COLOR}" stroke-width="1.5" />
            <g font-size="14">
              <g text-anchor="middle">
                <text x="80" y="478">0</text>
                <text x="260" y="478">{DOMAIN_LENGTH_M / 2:g}</text>
                <text x="440" y="478">{DOMAIN_LENGTH_M:g}</text>
                <text x="260" y="506" font-size="16">x (m)</text>
              </g>
              <g text-anchor="end">
                <text x="64" y="455">0</text>
                <text x="64" y="275">{DOMAIN_LENGTH_M / 2:g}</text>
                <text x="64" y="95">{DOMAIN_LENGTH_M:g}</text>
              </g>
              <text x="24" y="270" transform="rotate(-90 24 270)"
                    text-anchor="middle" font-size="16">y (m)</text>
            </g>
          </g>
        </svg>
        """
    )
    Path(__file__).with_name("reservoir.svg").write_text(svg, encoding="utf-8")


if __name__ == "__main__":
    main()
